const readPackagedHtml = require('./check-apk-asset.cjs');
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CLOCK_CHROMIUM_PATH,headless:true});
  try {
    const context=await browser.newContext({viewport:{width:1280,height:720},reducedMotion:'reduce'});
    const manifest=fs.readFileSync(path.join(__dirname,'AndroidManifest-tv.xml'),'utf8');
    const versionCode=manifest.match(/android:versionCode="([^"]+)"/)[1],versionName=manifest.match(/android:versionName="([^"]+)"/)[1];
    const baseURL='https://appassets.androidplatform.net/assets/glass-clock-tv.html';
    const pageURL=baseURL+'?v='+versionCode,previousURL=baseURL+'?v='+(Number(versionCode)-1);
    const source=fs.readFileSync(path.join(__dirname,'tv-src/local/fuguang/clock/tv/TVClockActivity.java'),'utf8');
    const csp=source.match(/headers\.put\("Content-Security-Policy", "([^"]+)"\)/)[1];
    const cacheControl=source.match(/headers\.put\("Cache-Control", "([^"]+)"\)/)[1];
    assert.equal(cacheControl,'no-store, max-age=0');
    const html=readPackagedHtml(`浮光·TV-${versionName}.apk`, 'glass-clock-tv.html');
    const requested=[];
    await context.route('**/*',route=>{
      requested.push(route.request().url());
      if([pageURL,previousURL].includes(route.request().url()))return route.fulfill({status:200,contentType:'text/html;charset=utf-8',headers:{'Content-Security-Policy':csp,'Cache-Control':cacheControl},body:html});
      return route.abort();
    });
    const page=await context.newPage(),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.clock.install();
    await page.goto(pageURL);
    await page.evaluate(()=>document.fonts.ready);
    await page.clock.runFor(100);
    const readiness="typeof window.clockTVRemote === 'function' && window.clockAppReady === true && window.clockTVReady === true";
    assert(source.includes(readiness),'use the exact native readiness contract');
    assert.equal(await page.evaluate(readiness),true);
    assert.equal(await page.locator('meta[name="clock-tv-version"]').getAttribute('content'),versionName,'bundled page identifies the exact installed version');
    const nativeProbe=JSON.parse(source.match(/private static final String STARTUP_PROBE = ("(?:\\.|[^"\\])*");/)[1]);
    const startupSnapshot=await page.evaluate(nativeProbe);
    assert.equal(startupSnapshot.ready,true);
    assert.equal(startupSnapshot.bootstrap,true);
    assert.equal(startupSnapshot.compatRejected,false);
    assert.equal(startupSnapshot.stage,'ready');
    assert.equal(startupSnapshot.firstError,'');
    assert(startupSnapshot.ua.includes('Chrome/'));
    assert.equal(await page.evaluate(()=>window.isSecureContext),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),true);
    assert.equal(await page.locator('#tv-close').isVisible(),true);
    assert.equal(await page.locator('#show-seconds').isChecked(),false);
    assert.equal(await page.locator('#digit-size').inputValue(),'140');
    assert.equal(await page.locator('#digit-weight').inputValue(),'800');
    assert.equal(await page.locator('.stick-world').count(),1);
    const remote=key=>page.evaluate(key=>window.clockTVRemote(key),key);
    assert.equal(await page.evaluate(()=>document.activeElement.id),'tv-close','first focus should let one press enter fullscreen');
    assert.equal(await remote('Enter'),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),false);
    assert.equal(await remote('Enter'),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),true);
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.tab),'display');
    assert.equal(await remote('ArrowRight'),true);
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.tab),'fonts');
    assert.equal(await remote('Enter'),true);
    assert(await page.locator('[data-font]').count()>=8);
    assert.equal(await remote('Escape'),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),false);
    assert.equal(await remote('Escape'),false,'second Back must allow native finish, never trap the user');
    assert.equal(await remote('Enter'),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),true);
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.tab),'fonts','reopening should retain the selected settings category');
    await page.locator('[data-tab="display"]').click();
    await page.getByRole('button',{name:'减小数字大小',exact:true}).click();
    assert.equal(await page.locator('#digit-size').inputValue(),'135');
    const saved=await page.evaluate(()=>localStorage.getItem('floating-light-clock-tv'));
    assert(saved,'settings must persist on the native secure origin');
    assert.equal(await remote('Menu'),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),false);
    assert.equal(await remote('Menu'),true);
    assert.equal(await page.locator('#tv-panel').isVisible(),true);
    await page.clock.fastForward(15100);
    assert.equal(await page.locator('#tv-panel').isVisible(),false,'15 seconds idle should enter pure clock');
    for(const url of [previousURL,pageURL]) {
      await page.goto(url);
      await page.clock.runFor(100);
      assert.equal(await page.locator('#digit-size').inputValue(),'135');
      assert.equal(await page.evaluate(()=>localStorage.getItem('floating-light-clock-tv')),saved,'version query must preserve the same settings origin');
    }
    assert.deepEqual(errors,[]);
    assert(!requested.some(url=>/fonts\.(googleapis|gstatic)/.test(url)));
    const report={passed:true,versionName,versionCode,pageURL,checks:['exact native readiness expression and diagnostic probe','secure bundled origin + native CSP','local HTML no-store and version query','bundled version matches Manifest','offline embedded fonts','large bold no-seconds defaults','single original companion','first Enter opens fullscreen and next Enter opens settings','settings category focus restored','fixed native direction/enter/menu keys','back closes then allows exit','15-second idle fullscreen','saved settings survive version URL change'],runtime:'desktop Chromium, not physical Android TV'};
    fs.mkdirSync(path.join(__dirname,'build-tv'),{recursive:true});
    fs.writeFileSync(path.join(__dirname,'build-tv/appassets-verification.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report,null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
